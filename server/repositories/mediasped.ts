const sharedGuides = ['freight-forwarder-cost', 'what-is-a-freight-forwarder', 'top-5-freight-forwarders', 'best-parcel-forwarding-service-europe-slovenia', 'is-a-freight-forwarder-cheaper', 'can-i-arrange-my-own-freight'];
const bilingualGuides = ['first-freight-shipment-checklist', 'fcl-vs-lcl-container-shipping', 'incoterms-costs-and-risk-explained', 'eu-import-customs-document-checklist', 'freight-quote-landed-costs', 'port-of-koper-import-planning', 'pallet-packing-road-freight', 'cold-chain-freight-checklist', 'air-freight-chargeable-weight', 'cargo-insurance-and-claims', 'dangerous-goods-shipping-preparation', 'shipment-templates-and-booking-pack'];
const languageSchema = z.enum(locales);
const plain = z.string().refine(value => !value.includes('<'), 'Use plain text without HTML tags.');
const required = plain.refine(value => value.trim().length > 0, 'This field is required.');
const slugSchema = z.string().max(200).regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, 'Use lowercase words separated by hyphens for the slug.');
const existingSlugSchema = z.string().regex(/^[\p{L}\p{N}]+(?:-[\p{L}\p{N}]+)*$/u).refine(value => Buffer.byteLength(value) <= 200);
const imageSchema = z.string().url().refine(value => { const url = new URL(value); return url.protocol === 'https:' && !url.username && !url.password; }, 'Use an HTTPS image URL without embedded credentials.');
const metadataSchema = z.object({ tags: z.array(required).max(50).optional(), meta_title: plain.optional(), meta_description: plain.optional(), featured_image: imageSchema.nullable().optional() }).strict();
const payloadSchema = z.object({
  id: z.string().uuid(), title: required, slug: slugSchema, excerpt: plain,
  content: z.string().min(1).max(2_000_000).refine(value => /^(?:(?:<p>(?:[^<]|<br>)*<\/p>|<h2>[^<]*<\/h2>)(?:\n|$))+$/s.test(value), 'The draft body must use escaped paragraph and heading markup generated by Blog Machine.'), language: languageSchema,
  tags: z.array(required).max(50), meta_title: plain.nullable(), meta_description: plain.nullable(), featured_image: imageSchema.nullable(),
  published: z.literal(false), published_at: z.null(),
}).strict();
export type MediaspedDraftPayload = z.infer<typeof payloadSchema>;
export type MediaspedRequest = typeof fetch;
export interface MediaspedConnection { configured: boolean; authenticated: boolean; admin: boolean; message: string; }

function assertNoStaticCollision(slug: string, language: string) {
  if (sharedGuides.includes(slug) || (['en', 'sl'].includes(language) && bilingualGuides.includes(slug))) throw new Error('This URL is reserved by a repository-managed Mediašped guide. Choose a different slug.');
}
const escape = (text: string) => text.replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]!));
function htmlBody(content: string) {
  return parseSections(content).flatMap(section => [
    ...(section.heading ? [`<h2>${escape(section.heading)}</h2>`] : []),
    ...section.paragraphs.map(paragraph => `<p>${escape(paragraph).replace(/\n/g, '<br>')}</p>`),
  ]).join('\n');
}

export function prepareMediaspedDraft(draft: ContentDraft, targetKey: string, metadata: Record<string, unknown>, id?: string): MediaspedDraftPayload {
  const language = languageSchema.parse(targetKey);
  const input = z.object({ title: required, slug: slugSchema, excerpt: plain, content: required }).parse(draft);
  const settings = metadataSchema.parse(metadata);
  assertNoStaticCollision(input.slug, language);
  return payloadSchema.parse({
    id: id ?? randomUUID(), title: input.title, slug: input.slug, excerpt: input.excerpt, content: htmlBody(input.content), language,
    tags: settings.tags ?? [], meta_title: settings.meta_title?.trim() || null, meta_description: settings.meta_description?.trim() || null, featured_image: settings.featured_image ?? null,
    published: false, published_at: null,
  });
}

function jwtRole(token: string) {
  try { return JSON.parse(Buffer.from(token.split('.')[1] ?? '', 'base64url').toString('utf8')).role as unknown; } catch { return undefined; }
}
export function mediaspedConfiguration(env: NodeJS.ProcessEnv, authenticated: boolean) {
  let base: URL;
  try { base = new URL(env.MEDIASPED_SUPABASE_URL ?? ''); } catch { throw new Error('Configure MEDIASPED_SUPABASE_URL and MEDIASPED_SUPABASE_ANON_KEY on the server.'); }
  if (base.origin !== projectUrl || base.pathname !== '/' || base.search || base.hash || base.username || base.password) throw new Error('MEDIASPED_SUPABASE_URL must match the verified Mediašped Supabase project.');
  const key = env.MEDIASPED_SUPABASE_ANON_KEY;
  if (!key || key.startsWith('sb_secret_') || jwtRole(key) === 'service_role') throw new Error('Configure the public MEDIASPED_SUPABASE_ANON_KEY. Service-role keys are not supported.');
  const token = env.MEDIASPED_SUPABASE_ACCESS_TOKEN;
  if (authenticated && (!token || jwtRole(token) !== 'authenticated')) throw new Error('Configure MEDIASPED_SUPABASE_ACCESS_TOKEN with a user session token. Service-role keys are not supported.');
  return { key, token };
}
async function call(request: MediaspedRequest, path: string, key: string, token: string, init: RequestInit = {}) {
  return request(`${projectUrl}${path}`, {
    ...init, headers: { apikey: key, Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', ...init.headers },
    redirect: 'error', signal: AbortSignal.timeout(20_000),
  });
}
async function authenticatedAdmin(env: NodeJS.ProcessEnv, request: MediaspedRequest) {
  const { key, token } = mediaspedConfiguration(env, true);
  const identityResponse = await call(request, '/auth/v1/user', key, token!, { method: 'GET' });
  if (!identityResponse.ok) return { key, token: token!, id: null, authenticated: false, admin: false };
  const identity = z.object({ id: z.string().uuid() }).safeParse(await identityResponse.json());
  if (!identity.success) return { key, token: token!, id: null, authenticated: false, admin: false };
  const roleResponse = await call(request, '/rest/v1/rpc/is_admin', key, token!, { method: 'POST', body: JSON.stringify({ _user_id: identity.data.id }) });
  const admin = roleResponse.ok && await roleResponse.json() === true;
  return { key, token: token!, id: identity.data.id, authenticated: true, admin };
}

export async function testMediaspedConnection(env: NodeJS.ProcessEnv, request: MediaspedRequest = fetch): Promise<MediaspedConnection> {
  try { mediaspedConfiguration(env, true); } catch (error) {
    return { configured: false, authenticated: false, admin: false, message: error instanceof Error ? error.message : 'Mediašped server configuration is incomplete.' };
  }
  try {
    const result = await authenticatedAdmin(env, request);
    return { configured: true, authenticated: result.authenticated, admin: result.admin, message: !result.authenticated
      ? 'The user session could not be verified. Refresh the Mediašped Supabase user access token.'
      : result.admin ? 'Mediašped authentication and administrator role are verified. No content was created or published.'
        : 'Authentication works, but administrator access was not verified. No content was created or published.' };
  } catch {
    return { configured: true, authenticated: false, admin: false, message: 'Could not verify the Mediašped connection. Check network access and the user session token. No content was changed.' };
  }
}

export async function listMediaspedArticles(targetKey: string, env: NodeJS.ProcessEnv, request: MediaspedRequest = fetch): Promise<ArticleSummary[]> {
  const language = languageSchema.parse(targetKey);
  const { key } = mediaspedConfiguration(env, false);
  try {
    const query = new URLSearchParams({ select: 'slug,title,excerpt,language', published: 'eq.true', language: `eq.${language}`, order: 'published_at.desc' });
    const response = await call(request, `/rest/v1/blog_posts?${query}`, key, key, { method: 'GET' });
    if (!response.ok) throw new Error('Read failed');
    const posts = z.array(z.object({ slug: existingSlugSchema, title: z.string(), excerpt: z.string().nullable(), language: languageSchema })).parse(await response.json());
    if (posts.some(post => post.language !== language)) throw new Error('Unexpected article language');
    return posts.map(post => ({ slug: post.slug, title: post.title, description: post.excerpt ?? '', url: `https://mediasped.com/${language}/blog/${encodeURIComponent(post.slug)}/` }));
  } catch { throw new Error('Could not read published Mediašped articles. Check the project connection and public blog access.'); }
}

function exactDraft(row: unknown, payload: MediaspedDraftPayload, author: string) {
  const parsed = payloadSchema.extend({ author_id: z.string().uuid() }).safeParse(row);
  if (!parsed.success || parsed.data.author_id !== author) return false;
  return Object.entries(payload).every(([key, value]) => JSON.stringify(parsed.data[key as keyof MediaspedDraftPayload]) === JSON.stringify(value));
}
export async function createMediaspedDraft(payload: MediaspedDraftPayload, env: NodeJS.ProcessEnv, request: MediaspedRequest = fetch) {
  const draft = payloadSchema.parse(payload);
  assertNoStaticCollision(draft.slug, draft.language);
  let auth;
  try { auth = await authenticatedAdmin(env, request); } catch { throw new Error('Could not verify Mediašped administrator access. No draft request was sent.'); }
  if (!auth.authenticated || !auth.admin || !auth.id) throw new Error('A verified Mediašped administrator session is required to save a remote draft.');
  const fields = ['id', 'title', 'slug', 'excerpt', 'content', 'language', 'tags', 'meta_title', 'meta_description', 'featured_image', 'published', 'published_at', 'author_id'].join(',');
  let response;
  try {
    response = await call(request, `/rest/v1/blog_posts?select=${fields}`, auth.key, auth.token, {
      method: 'POST', headers: { Prefer: 'return=representation' }, body: JSON.stringify({ ...draft, author_id: auth.id }),
    });
  } catch { throw new Error('The draft save outcome is unknown. Retry with the same draft ID to check it safely; do not generate a new ID.'); }
  let rows: unknown;
  if (response.status === 409) {
    const query = new URLSearchParams({ select: fields, id: `eq.${draft.id}`, language: `eq.${draft.language}` });
    try {
      const existing = await call(request, `/rest/v1/blog_posts?${query}`, auth.key, auth.token, { method: 'GET' });
      if (!existing.ok) throw new Error('Read failed');
      rows = await existing.json();
    } catch { throw new Error('Could not verify the conflicting draft. Retry with the same ID after checking the connection.'); }
  } else if (!response.ok) {
    throw new Error(`Mediašped rejected the draft save (HTTP ${response.status}). No publication was requested.`);
  } else {
    try { rows = await response.json(); } catch { throw new Error('The draft save response was incomplete. Retry with the same draft ID to verify it safely.'); }
  }
  if (!Array.isArray(rows) || rows.length !== 1 || !exactDraft(rows[0], draft, auth.id)) throw new Error('The remote row does not match this unpublished draft. It may be a slug collision, an edited draft, or a published article. Nothing was overwritten.');
  return { id: draft.id, slug: draft.slug, language: draft.language, published: false as const, articleUrl: `https://mediasped.com/${draft.language}/blog/${draft.slug}/`, message: 'Draft saved in Mediašped. It remains unpublished.' };
}
